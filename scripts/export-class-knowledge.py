#!/usr/bin/env python3
"""Export every Growing Minds class's lesson scripts as Growing Minds AI knowledge files.

Reads each lesson's script/script.py (TITLE, SUB, SLIDES, SOURCES, FLAGGED_CLAIMS)
from the class folders and writes one Markdown file per lesson into
knowledge/sources/, then the site's knowledge build turns those into AI cards:

    python3 scripts/export-class-knowledge.py            # all classes
    python3 scripts/export-class-knowledge.py --class Toddler
    node scripts/build-knowledge.mjs
    node scripts/corpus/certify.mjs

The scripts are parsed with ast.literal_eval, never executed. Edit script.py in the
class folder, not the output, then re-export: the output is overwritten each run,
and a class's stale files (a renamed or dropped lesson) are removed.

Each file is laid out for scripts/build-knowledge.mjs, which splits on Markdown
headings and caps chunks at 1,400 characters. This exporter keeps every section
under that cap itself (long sections become "(continued)" sections), so every
chunk keeps a meaningful heading for retrieval.

What goes in, per lesson:
  1. Overview: where the lesson sits in the class, its scope line, the opening.
  2. One section per slide: the narration, as written in script.py (not the
     narration-only PRONOUNCE spellings), with the few "on this slide" pointers
     reworded so the text stands on its own.
  3. Common myths: each FLAGGED_CLAIMS myth with what the research shows, except
     the "(old Lesson N)" entries, which are revision notes on an earlier draft.
  4. Research behind this lesson: each SOURCES finding with its citation and
     confidence note. Findings whose note asks for a confirmation are tagged,
     and the lesson's open publish checks (from the class README) are listed last.
OVERLAPS, ONSCREEN, CHANGES and course callbacks are internal and are left out.

This replaces the infant-only tools/export_knowledge.py in the Infant class folder;
its infant output is unchanged apart from the "Generated by" line.
"""

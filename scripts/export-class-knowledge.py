    ap = argparse.ArgumentParser()
    ap.add_argument("--classes", default=DEFAULT_CLASSES, help="folder holding Infant/, Toddler/, Preschool/")
    ap.add_argument("--class", dest="only", choices=sorted(CLASSES), help="export one class only")
    ap.add_argument("--out", default=DEFAULT_OUT)
    a = ap.parse_args()
    total = 0
    for name in ([a.only] if a.only else list(CLASSES)):
        course_dir = os.path.join(a.classes, name)
        if not os.path.isdir(course_dir):
            raise SystemExit(f"missing class folder: {course_dir}")
        rows, stale = export(name, course_dir, a.out)
        for f, n, mx in rows:
            print(f"{f}: {n} sections (longest {mx} chars)")
        for f in stale:
            print(f"removed stale {f}")
        total += len(rows)
    print(f"{total} lesson files written to {a.out}")

def clean(s):
    # House rule: no em dashes. En dashes become plain hyphens.
    s = s.replace(" — ", ", ").replace("—", ", ").replace("–", "-")
    return re.sub(r"[ \t]+", " ", s).strip()


def unslide(s):
    """Narration was written for video. Reword the few lines that point at the slide."""
    s = re.sub(r"\s*But look at the illustration on this slide\.", "", s)
    s = re.sub(r"\bLook at the (\w+ \w+) on this slide\.", r"Here are the \1.", s)
    s = s.replace("On one side of this slide:", "On one side:")
    s = s.replace("You can see this on the slide: three curves", "Picture three curves")
    return s.strip()


def myth_entry(myth, answer):
    """A FLAGGED_CLAIMS pair as (myth, what the research shows), or (None, None) to skip.

    Entries tagged "(old Lesson N)" or "(original Lesson N)" record how a claim from
    the class's earlier draft was handled ("Kept", "Reworded", "Dropped"). They are
    revision notes, not parent myths, and some of those claims were kept as true.
    Other entries may end in a provenance tag such as "(parent forums)" and open
    with the same verdict word; both are trimmed so the pair reads as a myth.
    """
    if re.search(r"\((old|original)\b", myth):
        return None, None
    myth = re.sub(r"\s*\((popular|parent|parenting)\b[^()]*\)$", "", myth.strip())
    answer = re.sub(r"^(Kept with the caveat|Kept|Reworded to what the studies show|Reworded|Replaced|Dropped)[.:]\s*",
                    "", answer.strip())
    return clean(myth), clean(answer[:1].upper() + answer[1:])


def read_script(path):
    """Top-level literal assignments of a script.py, parsed without running it."""
    out = {}
    for node in ast.parse(open(path, encoding="utf-8").read(), path).body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            try:
                out[node.targets[0].id] = ast.literal_eval(node.value)
            except ValueError:
                pass
    return out


def lessons(course_dir):
    out = []
    for d in sorted(os.listdir(course_dir)):
        m1 = re.match(r"Lesson0?(\d+)_(.+)$", d)
        m2 = re.match(r"Module(\d+)_Lesson(\d+)_(.+)$", d)
        if m1:
            mod, les, slug = 1, int(m1.group(1)), m1.group(2)
        elif m2:
            mod, les, slug = int(m2.group(1)), int(m2.group(2)), m2.group(3)
        else:
            continue
        path = os.path.join(course_dir, d, "script", "script.py")
        if os.path.exists(path):
            out.append((mod, les, slug, path))
    return sorted(out)


def open_checks(readme, mod, les):
    head = f"## Lesson {les} research notes" if mod == 1 else f"## Lesson {mod}.{les} research notes"
    if head not in readme:
        return ""
    sec = readme.split(head, 1)[1].split("\n## ", 1)[0]
    m = re.search(r"To confirm before publishing:\s*(.+)", sec)
    return clean(m.group(1)) if m else ""


def pack(heading, items, sep="\n\n"):
    """Pack text items under a heading, starting '(continued)' sections at the cap."""
    sections, buf = [], []
    for it in items:
        h = heading if not sections else f"{heading} (continued)"
        trial = f"## {h}\n\n" + sep.join(buf + [it])
        if buf and len(trial) > MAX:
            sections.append(f"## {h}\n\n" + sep.join(buf))
            buf = [it]
        else:
            buf.append(it)
    if buf:
        h = heading if not sections else f"{heading} (continued)"
        sections.append(f"## {h}\n\n" + sep.join(buf))
    return sections


def export(name, course_dir, outdir):
    cfg = CLASSES[name]
    course = cfg["course"]
    readme_path = os.path.join(course_dir, "README.md")
    readme = open(readme_path, encoding="utf-8").read() if os.path.exists(readme_path) else ""
    os.makedirs(outdir, exist_ok=True)
    written = []
    for mod, les, slug, path in lessons(course_dir):
        ns = read_script(path)
        num = f"{mod}.{les}"
        title = clean(ns["TITLE"])
        mtitle = clean(ns.get("MODULE_TITLE", cfg["module_titles"].get(mod, "")))
        label = f"Growing Minds class, {course}: Lesson {num}, {title}"
        bands = cfg["lesson_bands"].get(num, cfg["bands"])
        keywords = cfg["keywords"].get(num)
        if not keywords:
            raise SystemExit(f"{name} {num}: add search keywords for this lesson to CLASSES")
        parts = []

        for i, (stitle, paras) in enumerate(ns["SLIDES"]):
            stitle = clean(stitle)
            paras = [unslide(clean(p)) for p in paras if p.strip()]
            if i == 0:
                lead = (f"This is Lesson {num} of the Growing Minds class {course}"
                        f"{', Module ' + str(mod) + ' (' + mtitle + ')' if mtitle else ''}. "
                        f"It covers: {clean(ns.get('SUB', ''))}.").replace("..", ".")
                parts += pack("Overview", [lead] + paras)
                continue
            parts += pack(stitle, paras)

        myths = [f"Myth: {m}\nWhat the research shows: {r}"
                 for m, r in (myth_entry(a, b) for a, b in ns.get("FLAGGED_CLAIMS", [])) if m]
        if myths:
            parts += pack("Common myths", myths)

        research = []
        for claim, cite, conf in ns.get("SOURCES", []):
            if claim.lower().startswith("callback"):
                continue
            item = f"Finding: {clean(claim)}\nSources: {clean(cite)}\nConfidence: {clean(conf)}"
            if re.search(r"\b(confirm|verify|verification|recheck)\b", conf, re.I):
                item += "\nStatus: pending verification (a detail in this entry is still being checked)."
            research.append(item)
        checks = open_checks(readme, mod, les)
        if checks:
            research.append("Pending verification: these citation details are still being checked "
                            f"before publishing, so treat them as provisional: {checks}")
        if research:
            parts += pack("Research behind this lesson", research)

        header = ("<!--\n"
                  f"Growing Minds class script: {course}, Lesson {num}, {title}.\n"
                  "Generated by scripts/export-class-knowledge.py from the class folder's script/script.py. "
                  "Edit the script, then re-export; this file is overwritten.\n"
                  f"source-label: {label}\n"
                  f"age-bands: {', '.join(bands)}\n"
                  f"tags: {keywords}\n"
                  "-->\n\n")
        body = header + "\n\n".join(parts) + "\n"
        assert "—" not in body, f"em dash in {name} {num}"
        fname = f"{cfg['prefix']}-{mod}-{les}-{slug.lower().replace('_', '-')}.md"
        open(os.path.join(outdir, fname), "w", encoding="utf-8").write(body)
        written.append((fname, len(parts), max(len(p) for p in parts)))

    # A renamed or dropped lesson leaves its old file behind; remove it.
    keep = {f for f, _, _ in written}
    stale = [f for f in os.listdir(outdir)
             if re.match(rf"{cfg['prefix']}-\d+-\d+-.+\.md$", f) and f not in keep]
    for f in stale:
        os.remove(os.path.join(outdir, f))
    return written, stale



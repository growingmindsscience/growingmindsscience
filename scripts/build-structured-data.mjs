#!/usr/bin/env node
// Injects schema.org JSON-LD into article pages (Article + BreadcrumbList).
// Idempotent: rewrites the block between the STRUCTURED-DATA markers, so it is
// safe to re-run after editing or adding an article. Run:
//   node scripts/build-structured-data.mjs
// Dates are pulled from git history (first commit = datePublished, last =
// dateModified) so the markup never claims a date the repo cannot back up.

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const ORIGIN = "https://growingmindsscience.com";
const START = "<!-- STRUCTURED-DATA:start (generated by scripts/build-structured-data.mjs) -->";
const END = "<!-- STRUCTURED-DATA:end -->";

const AUTHOR = {
  "@type": "Person",
  name: "Matthew McArthur",
  jobTitle: "Child Development Specialist",
  url: `${ORIGIN}/about`,
};
const PUBLISHER = {
  "@type": "Organization",
  name: "Growing Minds Science",
  url: ORIGIN,
  logo: {
    "@type": "ImageObject",
    url: `${ORIGIN}/assets/img/original-logo-mark-no-words-512.png`,
  },
};

const ENTITIES = {
  "&quot;": '"', "&#34;": '"', "&apos;": "'", "&#39;": "'",
  "&amp;": "&", "&mdash;": "—", "&ndash;": "–",
  "&rsquo;": "’", "&lsquo;": "‘", "&ldquo;": "“",
  "&rdquo;": "”", "&hellip;": "…", "&nbsp;": " ",
};
const decode = (s) =>
  (s || "").replace(/&[a-z#0-9]+;/gi, (m) => ENTITIES[m] ?? m).trim();

const pick = (html, re) => {
  const m = html.match(re);
  return m ? m[1] : null;
};

const abs = (u) => {
  if (!u) return null;
  if (/^https?:\/\//.test(u)) return u;
  if (u.startsWith("/")) return ORIGIN + u;
  return `${ORIGIN}/${u.replace(/^\.?\//, "")}`;
};

function gitDate(file, first) {
  try {
    const args = first ? "--reverse --format=%aI" : "-1 --format=%aI";
    const out = execSync(`git log ${args} -- "${file}"`, { cwd: ROOT })
      .toString()
      .trim();
    return (first ? out.split("\n")[0] : out) || null;
  } catch {
    return null;
  }
}

// Matches the whole generated block, markers included.
const reEsc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const markerRe = () => new RegExp(`\\s*${reEsc(START)}[\\s\\S]*?${reEsc(END)}`);

// Strip the generated block so two revisions can be compared on their real
// content alone.
const stripGenerated = (s) => s.replace(markerRe(), "").replace(/\s+/g, " ").trim();

function gitShow(ref) {
  try {
    return execSync(`git show ${ref}`, { cwd: ROOT, stdio: ["ignore", "pipe", "ignore"] }).toString();
  } catch {
    return null; // path absent at that revision (e.g. the commit that added it)
  }
}

/**
 * dateModified = the newest commit that changed the article's ACTUAL content.
 *
 * Naively using `git log -1` makes this script non-idempotent: writing the block
 * creates a commit, which changes the date, which rewrites the block, forever.
 * So we walk the history newest-first and skip commits whose only effect on this
 * file was inside the generated markers.
 */
function contentModifiedDate(relPath) {
  try {
    const shas = execSync(`git log --format=%H -- "${relPath}"`, { cwd: ROOT })
      .toString().trim().split("\n").filter(Boolean);
    for (const sha of shas) {
      const cur = gitShow(`${sha}:${relPath}`);
      if (cur === null) continue;
      const prev = gitShow(`${sha}^:${relPath}`);
      // No parent version => the commit that introduced the file: real change.
      if (prev === null || stripGenerated(cur) !== stripGenerated(prev)) {
        return execSync(`git log -1 --format=%aI ${sha}`, { cwd: ROOT }).toString().trim() || null;
      }
    }
    return null;
  } catch {
    return null;
  }
}

function buildArticleLd(file, html) {
  const rawTitle = decode(pick(html, /<title>([^<]*)<\/title>/i) || "");
  const title = rawTitle.replace(/\s*[-–—]\s*Growing Minds Science\s*$/i, "").trim();
  const description = decode(pick(html, /<meta\s+name="description"\s+content="([^"]*)"/i) || "");
  const canonicalPath = pick(html, /<link\s+rel="canonical"\s+href="([^"]*)"/i);
  const url = abs(canonicalPath);
  const image = abs(pick(html, /<meta\s+property="og:image"\s+content="([^"]*)"/i));
  const rel = `articles/${file}`;
  const published = gitDate(rel, true);
  const modified = contentModifiedDate(rel);

  const article = {
    "@context": "https://schema.org",
    "@type": "Article",
    headline: title,
    description,
    inLanguage: "en",
    isAccessibleForFree: true,
    author: AUTHOR,
    publisher: PUBLISHER,
    ...(url ? { mainEntityOfPage: { "@type": "WebPage", "@id": url }, url } : {}),
    ...(image ? { image } : {}),
    ...(published ? { datePublished: published } : {}),
    ...(modified ? { dateModified: modified } : {}),
  };

  const breadcrumb = {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: [
      { "@type": "ListItem", position: 1, name: "Home", item: `${ORIGIN}/` },
      { "@type": "ListItem", position: 2, name: "Articles", item: `${ORIGIN}/articles/` },
      ...(url ? [{ "@type": "ListItem", position: 3, name: title, item: url }] : []),
    ],
  };

  return { title, blocks: [article, breadcrumb] };
}

function injectHead(html, jsonBlocks) {
  const script =
    `  ${START}\n` +
    `  <script type="application/ld+json">\n` +
    JSON.stringify(jsonBlocks, null, 2)
      .split("\n")
      .map((l) => "  " + l)
      .join("\n") +
    `\n  </script>\n` +
    `  ${END}`;

  const marker = markerRe();
  if (marker.test(html)) return html.replace(marker, "\n" + script);
  return html.replace(/<\/head>/i, script + "\n</head>");
}

// Waitlist / in-development classes. Course markup WITHOUT an offer node — the
// commerce layer owns pricing, and these classes are not yet purchasable, so we
// assert the course entity but make no price/availability claim. Toddlerhood is
// already live with its own hand-authored Course + Offer block and is left alone.
const CLASSES = {
  "birth-to-12-months.html": {
    name: "Birth to 12 Months: Cues, Attachment, and the First Year",
    audience: "Parents of infants aged 0–12 months",
  },
  "family-systems.html": {
    name: "Family Systems & Stress: How the Whole Family Shapes the Developing Child",
    audience: "Parents and caregivers of children aged 0–5",
  },
  "preschool.html": {
    name: "Preschool Years: Self-Regulation, Play, and Kindergarten Readiness",
    audience: "Parents of preschoolers aged 3–5",
  },
};

function buildClassLd(file, html, meta) {
  const description = decode(pick(html, /<meta\s+name="description"\s+content="([^"]*)"/i) || "");
  const url = abs(pick(html, /<link\s+rel="canonical"\s+href="([^"]*)"/i));
  const course = {
    "@context": "https://schema.org",
    "@type": "Course",
    name: meta.name,
    description,
    inLanguage: "en",
    ...(url ? { url } : {}),
    provider: { "@type": "Organization", name: "Growing Minds Science", url: ORIGIN },
    author: { "@type": "Person", name: "Matthew McArthur", jobTitle: "Child Development Specialist" },
    courseMode: "online",
    educationalLevel: "General",
    audience: {
      "@type": "EducationalAudience",
      educationalRole: "parent",
      audienceType: meta.audience,
    },
    hasCourseInstance: {
      "@type": "CourseInstance",
      courseMode: "online",
      courseSchedule: { "@type": "Schedule", repeatFrequency: "self-paced" },
    },
  };
  const breadcrumb = {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: [
      { "@type": "ListItem", position: 1, name: "Home", item: `${ORIGIN}/` },
      { "@type": "ListItem", position: 2, name: "Classes", item: `${ORIGIN}/classes/` },
      ...(url ? [{ "@type": "ListItem", position: 3, name: meta.name, item: url }] : []),
    ],
  };
  return { title: meta.name, blocks: [course, breadcrumb] };
}

function processDir(subdir, builder, filter) {
  const dir = join(ROOT, subdir);
  const files = readdirSync(dir).filter(filter);
  let changed = 0;
  for (const file of files) {
    const path = join(dir, file);
    const html = readFileSync(path, "utf8");
    const { title, blocks } = builder(file, html);
    const next = injectHead(html, blocks);
    if (next !== html) {
      writeFileSync(path, next);
      changed++;
      console.log(`  ✓ ${subdir}/${file} — "${title}"`);
    } else {
      console.log(`  · ${subdir}/${file} — unchanged`);
    }
  }
  return { changed, total: files.length };
}

console.log("Articles:");
const a = processDir(
  "articles",
  (f, h) => buildArticleLd(f, h),
  (f) => f.endsWith(".html") && f !== "index.html",
);

console.log("\nClasses (waitlist — Course entity, no offer):");
const c = processDir(
  "classes",
  (f, h) => buildClassLd(f, h, CLASSES[f]),
  (f) => Object.prototype.hasOwnProperty.call(CLASSES, f),
);

console.log(
  `\nStructured data: ${a.changed}/${a.total} articles, ${c.changed}/${c.total} classes updated.`,
);
